"""Migration: Add db_alias column to api_hub_sql_definitions.

- Adds db_alias column (default='default') if not exists
- Drops old unique constraint on name alone
- Adds new composite unique constraint on (name, db_alias)

Safe to run multiple times (idempotent).

Usage:
    python -m scripts.migrate_sql_def_db_alias
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sqlalchemy import text

from app.db.session import engine


def main():
    with engine.connect() as conn:
        # 1. Add db_alias column if not exists
        result = conn.execute(text("""
            SELECT column_name FROM information_schema.columns
            WHERE table_name = 'api_hub_sql_definitions' AND column_name = 'db_alias'
        """))
        if result.fetchone() is None:
            conn.execute(text("""
                ALTER TABLE api_hub_sql_definitions
                ADD COLUMN db_alias VARCHAR(64) NOT NULL DEFAULT 'default'
            """))
            print("Added db_alias column.")
        else:
            print("db_alias column already exists.")

        # 2. Drop old unique constraint/index on name alone (try common names)
        for constraint_name in [
            "api_hub_sql_definitions_name_key",  # auto-generated by PG for unique=True column
            "uq_sql_definitions_name",
        ]:
            conn.execute(text(f"ALTER TABLE api_hub_sql_definitions DROP CONSTRAINT IF EXISTS {constraint_name}"))
        # Also drop unique index (SQLAlchemy index=True with unique=True)
        conn.execute(text("DROP INDEX IF EXISTS ix_api_hub_sql_definitions_name"))
        # Recreate as non-unique index (useful for name lookups)
        conn.execute(text("CREATE INDEX IF NOT EXISTS ix_sql_def_name ON api_hub_sql_definitions (name)"))
        print("Dropped old unique constraint/index on name (if existed).")

        # 3. Create composite unique constraint
        conn.execute(text("""
            DO $$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1 FROM pg_constraint WHERE conname = 'uq_sql_def_name_db_alias'
                ) THEN
                    ALTER TABLE api_hub_sql_definitions
                    ADD CONSTRAINT uq_sql_def_name_db_alias UNIQUE (name, db_alias);
                END IF;
            END $$;
        """))
        print("Ensured composite unique constraint (name, db_alias).")

        # 4. Add index on db_alias if not exists
        conn.execute(text("""
            CREATE INDEX IF NOT EXISTS ix_sql_def_db_alias ON api_hub_sql_definitions (db_alias)
        """))
        print("Ensured index on db_alias.")

        conn.commit()

    print("\nMigration completed successfully.")


if __name__ == "__main__":
    main()
